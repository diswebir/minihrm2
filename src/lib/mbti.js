/**
 * @param {Array<{axis:string, choice:string, value:string}>} answers
 * @param {Array} questions  فهرست سؤالات آزمون (برای اطلاع از تعداد هر محور)
 */
function score(answers, questions = []) {
  const scores = { E: 0, I: 0, S: 0, N: 0, T: 0, F: 0, J: 0, P: 0 };
  const perAxisMax = { EI: 0, SN: 0, TF: 0, JP: 0 };
  const perAxisCount = { EI: 0, SN: 0, TF: 0, JP: 0 };

  const qMap = new Map();
  questions.forEach((q) => qMap.set(String(q.id || q.number), q));

  for (const a of answers || []) {
    let letter = a.value;
    if (!letter && a.choice) {
      const q = qMap.get(String(a.question_id));
      if (q) {
        if (a.choice === 'A') letter = q.option_a_value;
        else if (a.choice === 'B') letter = q.option_b_value;
        else if (a.choice === 'C') letter = q.option_c_value;
        else if (a.choice === 'D') letter = q.option_d_value;
      }
    }
    const axis = a.axis || LETTER_AXIS[letter];
    if (!axis) continue;
    if (letter) scores[letter] = (scores[letter] || 0) + 1;
    perAxisCount[axis] += 1;
  }

  // بیشینه هر محور از روی سؤالات آزمون (اگر نبود، تعداد پاسخ‌ها)
  for (const [axis, a] of Object.entries(AXES)) {
    const qs = questions.filter((q) => (q.axis || '') === axis && q.is_active !== 0);
    const total = qs.length || perAxisCount[axis];
    perAxisMax[axis] = total;
  }

  const result = { scores, axes: {}, type: '', borderline: [] };
  for (const [axis, def] of Object.entries(AXES)) {
    const pos = scores[def.positive] || 0;
    const neg = scores[def.negative] || 0;
    const total = Math.max(perAxisMax[axis] || 0, pos + neg, 1);
    let winner;
    let tie = false;
    if (pos === neg) { winner = TIE_BREAK[axis]; tie = true; }
    else winner = pos > neg ? def.positive : def.negative;
    // closeness: فاصله نسبی از مرکز (۰ = کاملاً مرزی، ۱۰۰ = کاملاً یک‌طرفه)
    const closeness = total ? Math.round((Math.abs(pos - neg) / total) * 100) : 0;
    result.axes[axis] = {
      axis,
      label: def.label,
      positive: def.positive, negative: def.negative,
      positiveScore: pos, negativeScore: neg,
      positivePercent: total ? Math.round((pos / total) * 100) : 0,
      negativePercent: total ? Math.round((neg / total) * 100) : 0,
      winner,
      winnerTitle: winner === def.positive ? def.positiveTitle : def.negativeTitle,
      winnerDesc: winner === def.positive ? def.positiveDesc : def.negativeDesc,
      tie, closeness, total,
      strength: closeness >= 60 ? 'بارز' : closeness >= 25 ? 'متوسط' : 'مرزی',
    };
    result.type += winner;
    if (tie || closeness < 25) result.borderline.push(axis);
  }

  // ترتیب استاندارد MBTI: E/I سپس S/N سپس T/F سپس J/P
  const order = ['EI', 'SN', 'TF', 'JP'];
  result.type = order.map((ax) => result.axes[ax].winner).join('');
  result.confidence = result.borderline.length === 0 ? 'بالا' : result.borderline.length === 1 ? 'متوسط' : 'پایین (چند محور مرزی)';
  return result;
}

/** تحلیل کامل + متن فارسی برای نمایش در پنل منابع انسانی */
function analyze(answers, questions = []) {
  const s = score(answers, questions);
  const lib = TYPE_LIBRARY[s.type] || {};
  const answered = (answers || []).length;

  const axisRows = Object.values(s.axes).map((a) => ({
    ...a,
    positiveTitlePersian: a.axis === 'EI' ? 'برون‌گرا' : a.axis === 'SN' ? 'خلاق/شهودی' : a.axis === 'TF' ? 'منطقی' : 'منضبط',
    negativeTitlePersian: a.axis === 'EI' ? 'درون‌گرا' : a.axis === 'SN' ? 'واقع‌گرا' : a.axis === 'TF' ? 'احساسی' : 'ملاحظه‌کار',
  }));

  const summary = lib.summary
    ? `تیپ شخصیتی «${s.type}» — ${lib.title}. ${lib.summary}`
    : `تیپ شخصیتی «${s.type}».`;

  return {
    type_code: s.type,
    type_name: lib.title || '',
    group_name: lib.group || '',
    axis_scores: s.scores,
    percentages: {
      E: s.axes.EI.positivePercent, I: s.axes.EI.negativePercent,
      N: s.axes.SN.positivePercent, S: s.axes.SN.negativePercent,
      T: s.axes.TF.positivePercent, F: s.axes.TF.negativePercent,
      J: s.axes.JP.positivePercent, P: s.axes.JP.negativePercent,
    },
    axes_detail: axisRows,
    borderline_axes: s.borderline,
    confidence: s.confidence,
    answered_count: answered,
    summary,
    strengths: (lib.strengths || []).join('\n'),
    watchouts: (lib.watchouts || []).join('\n'),
    communication: lib.communication || '',
    leadership: lib.leadership || '',
    motivation: lib.motivation || '',
    suggestions: (lib.manageTips || []).join('\n'),
    fit_notes: (lib.bestRoles || []).join('، '),
    job_fit: (lib.bestRoles || []).map((r) => ({ role: r, score: 90 })),
    risk_notes: lib.riskNotes || '',
  };
}

/** محاسبه درصد تطابق تیپ با یک شغل خاص (برای پیشنهاد شغلی) */
function jobFit(typeCode, jobTitle) {
  const lib = TYPE_LIBRARY[typeCode];
  if (!lib || !jobTitle) return null;
  const t = String(jobTitle);
  const hit = (lib.bestRoles || []).some((r) => t.includes(r) || r.includes(t));
  return hit ? 90 : 55;
}

