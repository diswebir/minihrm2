'use strict';
/**
 * سازندهٔ PDF سبک و بدون وابستگی خارجی (سازگار با هاست cPanel)
 * ----------------------------------------------------------------------------
 * فایل PDF با متن فارسی را می‌سازد؛ متن به‌صورت تصویر برداری (Path) رسم
 * نمی‌شود بلکه از قالب HTML مرورگر برای چاپ استفاده می‌کنیم؛ این ماژول برای
 * مواردی است که خروجی فایل PDF واقعی لازم است (بایگانی/ارسال).
 * چون فونت‌های فارسی باید جاسازی شوند، PDF پایه به‌صورت «چاپ از مرورگر» با
 * تنظیمات @page A4 در CSS ارائه می‌شود و این ماژول فقط متادیتا/نام‌گذاری
 * فایل را فراهم می‌کند.
 */
function fileName(prefix, parts = []) {
  const clean = (v) => String(v || '').replace(/[^\p{L}\p{N}\-_]+/gu, '-').replace(/-+/g, '-');
  return [prefix, ...parts.map(clean)].filter(Boolean).join('-') + '.pdf';
}
module.exports = { fileName };
